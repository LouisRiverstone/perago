// Package database stores perago's queue, failed jobs, batches and cache in a SQL database. It
// depends on database/sql alone and speaks PostgreSQL, CockroachDB, Redshift, MySQL, MariaDB,
// SQLite, SQL Server and Oracle: open the connection with the driver you already use and wrap it
// with New.
//
//	sqlDB, _ := sql.Open("pgx", dsn)
//	db, _ := database.New(sqlDB, "postgres")
//	driver := database.NewDriver(db, database.DriverOptions{})
//
// Create the tables at startup with Install, from the SQL TableSQL returns (make:queue-table
// writes it to a file), or, on migro, with the migrations of github.com/LouisRiverstone/perago/migro.
package database

import (
	"context"
	"fmt"
	"hash/fnv"
	"strconv"
	"strings"

	"github.com/LouisRiverstone/perago"
)

// Default table names (Laravel's).
const (
	JobsTable    = "jobs"
	FailedTable  = "failed_jobs"
	BatchesTable = "job_batches"
	CacheTable   = "cache"
)

// CacheValueLength is the longest value the database cache stores.
const CacheValueLength = 4000

// Tables names the tables Install creates; empty names use the defaults.
type Tables struct {
	Jobs, Failed, Batches, Cache string
}

func or(v, def string) string {
	if v == "" {
		return def
	}
	return v
}

type kind int

const (
	kindID kind = iota // big auto-increment primary key
	kindString
	kindText
	kindInteger
	kindBigInt
)

type column struct {
	name     string
	kind     kind
	length   int
	nullable bool
	primary  bool
	def      string
}

type tableDef struct {
	columns []column
	indexes [][]string
}

func str(name string, length int) column { return column{name: name, kind: kindString, length: length} }
func text(name string) column            { return column{name: name, kind: kindText} }
func integer(name string) column         { return column{name: name, kind: kindInteger} }
func bigint(name string) column          { return column{name: name, kind: kindBigInt} }
func (c column) null() column            { c.nullable = true; return c }
func (c column) pk() column              { c.primary = true; return c }
func (c column) dflt(v string) column    { c.def = v; return c }

// definitions mirror the migro migrations column for column, so both create the same tables.
var definitions = map[string]tableDef{
	JobsTable: {
		columns: []column{
			{name: "id", kind: kindID}, str("queue", 255), text("payload"), integer("attempts").dflt("0"),
			bigint("reserved_at").null(), bigint("available_at"), bigint("created_at"),
		},
		indexes: [][]string{{"queue"}, {"queue", "reserved_at", "available_at"}},
	},
	FailedTable: {
		columns: []column{
			str("uuid", 36).pk(), str("connection", 255), str("queue", 255), text("payload"), text("exception"), bigint("failed_at"),
		},
		indexes: [][]string{{"queue"}, {"failed_at"}},
	},
	BatchesTable: {
		columns: []column{
			str("id", 36).pk(), str("name", 255), integer("total_jobs"), integer("pending_jobs"), integer("failed_jobs"),
			text("failed_job_ids"), text("options").null(), bigint("cancelled_at").null(), bigint("created_at"), bigint("finished_at").null(),
		},
		indexes: [][]string{{"created_at"}},
	},
	CacheTable: {
		columns: []column{str("key", 255).pk(), str("value", CacheValueLength), bigint("expiration")},
		indexes: [][]string{{"expiration"}},
	},
}

func (d Dialect) columnType(c column) string {
	switch c.kind {
	case kindString:
		return d.stringType(c.length)
	case kindText:
		return d.textType()
	case kindInteger:
		if d == Oracle {
			return "NUMBER(10)"
		}
		return "integer"
	case kindBigInt:
		if d == Oracle {
			return "NUMBER(19)"
		}
		if d == SQLite {
			return "integer"
		}
		return "bigint"
	}
	return d.autoIncrement()
}

func (d Dialect) stringType(n int) string {
	switch d {
	case SQLServer:
		return "nvarchar(" + strconv.Itoa(n) + ")"
	case Oracle:
		return "VARCHAR2(" + strconv.Itoa(n) + ")"
	}
	return "varchar(" + strconv.Itoa(n) + ")"
}

// textType holds payloads: LONGTEXT on MySQL and MariaDB, where TEXT stops at 64 KB.
func (d Dialect) textType() string {
	switch {
	case d.mysqlFamily():
		return "longtext"
	case d == Redshift:
		return "varchar(65535)"
	case d == SQLServer:
		return "nvarchar(max)"
	case d == Oracle:
		return "CLOB"
	}
	return "text"
}

func (d Dialect) autoIncrement() string {
	switch d {
	case Postgres:
		return "bigserial primary key"
	case CockroachDB:
		return "bigint generated by default as identity primary key"
	case Redshift:
		return "bigint identity(1,1) primary key"
	case MySQL, MariaDB:
		return "bigint unsigned not null auto_increment primary key"
	case SQLite:
		return "integer primary key autoincrement"
	case SQLServer:
		return "bigint identity(1,1) not null primary key"
	}
	return "NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
}

const maxIdentLen = 63

// indexName matches migro's: table_cols_index, hashed when longer than 63 characters.
func indexName(table string, cols []string) string {
	raw := strings.ReplaceAll(table, ".", "_") + "_" + strings.Join(cols, "_") + "_index"
	if len(raw) <= maxIdentLen {
		return raw
	}
	h := fnv.New32a()
	_, _ = h.Write([]byte(raw))
	return fmt.Sprintf("%s_%08x", raw[:maxIdentLen-9], h.Sum32())
}

// TableSQL returns the statements creating one of perago's tables: table is JobsTable,
// FailedTable, BatchesTable or CacheTable, and name the table's name ("" keeps the default).
func TableSQL(d Dialect, table, name string) ([]string, error) {
	def, ok := definitions[table]
	if !ok {
		return nil, perago.Newf(perago.InvalidConfig, "database: unknown table %q", table)
	}
	if _, ok := aliases[string(d)]; !ok {
		return nil, perago.Newf(perago.InvalidConfig, "database: unknown dialect %q", d)
	}
	name = or(name, table)
	cols := make([]string, len(def.columns))
	for i, c := range def.columns {
		cols[i] = d.columnSQL(c)
	}
	out := []string{"CREATE TABLE " + d.Quote(name) + " (" + strings.Join(cols, ", ") + ")"}
	if d == Redshift {
		return out, nil // Redshift has no indexes
	}
	for _, idx := range def.indexes {
		quoted := make([]string, len(idx))
		for i, c := range idx {
			quoted[i] = d.Quote(c)
		}
		out = append(out, "CREATE INDEX "+d.Quote(indexName(name, idx))+" ON "+d.Quote(name)+" ("+strings.Join(quoted, ", ")+")")
	}
	return out, nil
}

func (d Dialect) columnSQL(c column) string {
	s := d.Quote(c.name) + " " + d.columnType(c)
	if c.kind == kindID {
		return s
	}
	if c.def != "" {
		s += " DEFAULT " + c.def
	}
	if c.nullable {
		return s + " NULL"
	}
	s += " NOT NULL"
	if c.primary {
		s += " PRIMARY KEY"
	}
	return s
}

// Install creates every table that does not exist yet. Run it on a connection, not inside a
// transaction: the existence probe fails on purpose for missing tables.
func Install(ctx context.Context, db *DB, t Tables) error {
	steps := []struct{ table, name string }{
		{JobsTable, or(t.Jobs, JobsTable)},
		{FailedTable, or(t.Failed, FailedTable)},
		{BatchesTable, or(t.Batches, BatchesTable)},
		{CacheTable, or(t.Cache, CacheTable)},
	}
	for _, st := range steps {
		if db.hasTable(ctx, st.name) {
			continue
		}
		stmts, err := TableSQL(db.dialect, st.table, st.name)
		if err != nil {
			return err
		}
		for _, s := range stmts {
			if _, err := db.exec(ctx, perago.InvalidConfig, s); err != nil {
				return perago.Wrap(perago.InvalidConfig, err, "create table %s", st.name)
			}
		}
	}
	return nil
}

func (db *DB) hasTable(ctx context.Context, name string) bool {
	rows, err := db.query(ctx, "SELECT 1 FROM "+db.dialect.Quote(name)+" WHERE 1 = 0")
	if err != nil {
		return false
	}
	_ = rows.Close()
	return true
}
